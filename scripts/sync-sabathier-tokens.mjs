// Copies the design tokens of the site (repo emiliensabathier/site, src/site/{tokens,nav}.css) into
// the Terminal. Never edit src/styles/sabathier-tokens.css by hand: change the site, then run
//   node scripts/sync-sabathier-tokens.mjs [siteDir]           (default ~/projets/site/app)
//   node scripts/sync-sabathier-tokens.mjs --check [siteDir]   exit 1 if the copy is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';

export function buildTokens(tokensCss, navCss) {
  const body = `${tokensCss.trimEnd()}\n\n${navCss.trimEnd()}\n`.replaceAll('/site/fonts/', '/site-fonts/');
  const hash = createHash('sha256').update(body).digest('hex');
  return `/* GENERATED by scripts/sync-sabathier-tokens.mjs from emiliensabathier/site src/site/{tokens,nav}.css. Do not edit. body-sha256: ${hash} */\n${body}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const siteDir = args.find((a) => !a.startsWith('--')) ?? join(homedir(), 'projets', 'site', 'app');
  const src = (f) => readFileSync(join(siteDir, 'src', 'site', f), 'utf8');
  const out = fileURLToPath(new URL('../src/styles/sabathier-tokens.css', import.meta.url));
  const next = buildTokens(src('tokens.css'), src('nav.css'));
  if (check) {
    const same = existsSync(out) && readFileSync(out, 'utf8') === next;
    console.log(same ? 'sabathier-tokens.css is up to date' : 'sabathier-tokens.css is stale: run the sync');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(out, next);
  console.log(`wrote ${out}`);
}
